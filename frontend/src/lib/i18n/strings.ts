export const STRINGS: Record<Lang, Record<StringKey, string>> = { en, me };

export type Vars = Record<string, string | number>;

/** The string for `key` in `lang` with its `{placeholders}` filled. */
export function translate(lang: Lang, key: StringKey, vars?: Vars): string {
  const text = STRINGS[lang][key] ?? STRINGS.en[key];
  return vars ? text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m)) : text;
}

export type Translate = (key: StringKey, vars?: Vars) => string;

export const isLang = (value: unknown): value is Lang => typeof value === "string" && (LANGS as readonly string[]).includes(value);
